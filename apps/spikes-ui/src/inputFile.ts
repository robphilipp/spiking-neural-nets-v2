// ----- times -----

/** "500 ms", "1.5 s", "2 min" or a number (ms) → ms. */
export function parseTime(value: unknown, what: string): number {
  if (typeof value === "number" && Number.isFinite(value) && value >= 0) return value;
  if (typeof value === "string") {
    const m = /^\s*(\d+(?:\.\d*)?|\.\d+)\s*(ns|µs|us|ms|s|min|h)?\s*$/.exec(value);
    if (m) {
      const factor: Record<string, number> = { ns: 1e-6, "µs": 1e-3, us: 1e-3, ms: 1, s: 1e3, min: 6e4, h: 3.6e6 };
      return Number(m[1]) * factor[m[2] ?? "ms"]!;
    }
  }
  throw new InputFileError(`${what} must be a time like "500 ms" or "1 s" (got ${JSON.stringify(value)})`);
}

/** ms → "1.5 s" or "250 ms". */
export function formatTime(ms: number): string {
  return ms >= 1000 && ms % 100 === 0 ? `${ms / 1000} s` : `${ms} ms`;
}

/** "uniform(1 s, 2 s)" or "normal(10, 2)" (times or plain numbers): a random value; otherwise null. */
export function parseRandom(value: unknown, time: boolean, what: string): Random | null {
  if (typeof value !== "string") return null;
  const m = /^\s*(uniform|normal)\(\s*([^,]+?)\s*,\s*([^)]+?)\s*\)\s*$/.exec(value);
  if (!m) return null;
  const arg = (x: string) => {
    if (time) return parseTime(x, what);
    const n = Number(x);
    if (!Number.isFinite(n)) throw new InputFileError(`${what}: ${x} isn't a number`);
    return n;
  };
  const [a, b] = [arg(m[2]!), arg(m[3]!)];
  if (m[1] === "uniform") {
    if (a > b) throw new InputFileError(`${what}: uniform(${m[2]}, ${m[3]}): the low end is above the high end`);
    return { uniform: [a, b] };
  }
  if (b < 0) throw new InputFileError(`${what}: normal(${m[2]}, ${m[3]}): the standard deviation can't be negative`);
  return { normal: [a, b] };
}

export const meanOf = (r: Random) => ("uniform" in r ? (r.uniform[0] + r.uniform[1]) / 2 : r.normal[0]);

export function formatRandom(r: Random, time: boolean): string {
  const f = (x: number) => (time ? formatTime(x) : String(x));
  return "uniform" in r ? `uniform(${f(r.uniform[0])}, ${f(r.uniform[1])})` : `normal(${f(r.normal[0])}, ${f(r.normal[1])})`;
}

// ----- reading and writing -----

const num = (v: unknown, what: string, ok: (n: number) => boolean = Number.isFinite): number => {
  if (typeof v !== "number" || !ok(v)) throw new InputFileError(`${what} isn't valid (${JSON.stringify(v)})`);
  return v;
};

function targetsOf(v: unknown, what: string): Targets {
  const t = (v ?? {}) as Record<string, unknown>;
  const keys = ["prefix", "regex", "set"].filter((k) => typeof t[k] === "string");
  if (keys.length !== 1) throw new InputFileError(`${what}: neurons must be { prefix = "…" }, { regex = "…" } or { set = "…" }`);
  const k = keys[0]!;
  return { [k]: t[k] as string } as Targets;
}

function encodingOf(v: unknown, what: string): Encoding {
  const e = (v ?? {}) as Record<string, unknown>;
  switch (e.kind) {
    case "current":
      return { type: "current", gainMv: num(e.gain_mv, `${what}: encoding.gain_mv`) };
    case "rate":
      return { type: "rate", maxHz: num(e.max_hz, `${what}: encoding.max_hz`, (n) => n > 0), mv: num(e.mv, `${what}: encoding.mv`) };
    case "threshold":
      return { type: "threshold", level: num(e.level, `${what}: encoding.level`, (n) => n > 0), mv: num(e.mv, `${what}: encoding.mv`) };
    case "spikes":
      return { type: "spikes", mv: num(e.mv, `${what}: encoding.mv`) };
    default:
      throw new InputFileError(`${what}: encoding.kind must be current, rate or threshold (got ${JSON.stringify(e.kind)})`);
  }
}

function encodingToml(e: Encoding): Record<string, unknown> {
  switch (e.type) {
    case "current":
      return { kind: "current", gain_mv: e.gainMv };
    case "rate":
      return { kind: "rate", max_hz: e.maxHz, mv: e.mv };
    case "threshold":
      return { kind: "threshold", level: e.level, mv: e.mv };
    case "spikes":
      return { kind: "spikes", mv: e.mv };
  }
}

/** Reads an input file (`file` names it in errors). */
export function parseInputFile(text: string, file = "the input file"): InputFile {
  let toml: Record<string, unknown>;
  try {
    toml = parse(text) as Record<string, unknown>;
  } catch (e) {
    throw new InputFileError(`${file}: ${e instanceof Error ? e.message : String(e)}`);
  }
  const list = toml.source ?? [];
  if (!Array.isArray(list)) throw new InputFileError(`${file}: [[source]] must be a list of sources`);
  const names = new Set<string>();
  const sources = list.map((raw, i): Source => {
    const r = { ...(raw as Record<string, unknown>) };
    const name = typeof r.name === "string" && r.name ? r.name : `source ${i + 1}`;
    const what = `${file}: source '${name}'`;
    // Random settings: kept aside, their mean in the plain field.
    const random: Partial<Record<RandomField, Random>> = {};
    for (const field of ["start", "duration", "mv", "hz", "period"] as RandomField[]) {
      const x = parseRandom(r[field], TIME_FIELDS.includes(field), `${what}: ${field}`);
      if (x) {
        random[field] = x;
        r[field] = meanOf(x);
      }
    }
    if (r.scope !== undefined && r.scope !== "run" && r.scope !== "trial") {
      throw new InputFileError(`${what}: scope must be "run" or "trial" (got ${JSON.stringify(r.scope)})`);
    }
    if (names.has(name)) throw new InputFileError(`${file}: two sources are named '${name}'`);
    names.add(name);
    const base: Base = {
      name,
      targets: targetsOf(r.neurons, what),
      start: r.start === undefined ? 0 : parseTime(r.start, `${what}: start`),
      duration: r.duration === undefined ? null : parseTime(r.duration, `${what}: duration`),
      enabled: r.enabled === undefined ? true : r.enabled === true,
      ...(r.scope === "trial" ? { scope: "trial" as const } : {}),
      ...(Object.keys(random).length ? { random } : {}),
    };
    switch (r.kind) {
      case "pulse": {
        const at = r.at === undefined ? [] : Array.isArray(r.at) ? r.at : [r.at];
        return { ...base, kind: "pulse", at: at.map((t) => parseTime(t, `${what}: at`)), mv: num(r.mv, `${what}: mv`) };
      }
      case "poisson":
        return { ...base, kind: "poisson", hz: num(r.hz, `${what}: hz`, (n) => n > 0), mv: num(r.mv, `${what}: mv`) };
      case "periodic":
        return { ...base, kind: "periodic", period: parseTime(r.period, `${what}: period`), mv: num(r.mv, `${what}: mv`) };
      case "signal": {
        const formula = typeof r.formula === "string" ? r.formula : "";
        try {
          compile(formula);
        } catch (e) {
          throw new InputFileError(`${what}: formula: ${e instanceof SignalError ? `${e.message} (at character ${e.position + 1})` : String(e)}`);
        }
        const encoding = encodingOf(r.encoding, what);
        if (encoding.type === "spikes") throw new InputFileError(`${what}: a signal's encoding is current, rate or threshold`);
        const sample = r.sample === undefined ? 1 : parseTime(r.sample, `${what}: sample`);
        if (!(sample > 0)) throw new InputFileError(`${what}: sample must be positive`);
        const channels = r.channels === undefined ? undefined : num(r.channels, `${what}: channels`, (n) => Number.isInteger(n) && n >= 1);
        const layout = layoutOf(r, "signal", what);
        return checked({ ...base, kind: "signal", formula, sample, encoding, ...(channels === undefined ? {} : { channels }), ...(layout ? { layout } : {}) }, what);
      }
      case "file": {
        if (typeof r.data !== "string" || !r.data) throw new InputFileError(`${what}: data must name a [[data]] table, like data = "odour"`);
        const encoding = encodingOf(r.encoding, what);
        if (encoding.type === "spikes") throw new InputFileError(`${what}: a file's encoding is current, rate or threshold`);
        const sample = r.sample === undefined ? 1 : parseTime(r.sample, `${what}: sample`);
        if (!(sample > 0)) throw new InputFileError(`${what}: sample must be positive`);
        const gain = r.gain === undefined ? 1 : num(r.gain, `${what}: gain`);
        const channels = r.channels === undefined ? undefined : num(r.channels, `${what}: channels`, (n) => Number.isInteger(n) && n >= 1);
        const layout = layoutOf(r, "file", what);
        return checked({ ...base, kind: "file", data: r.data, gain, sample, encoding, ...(channels === undefined ? {} : { channels }), ...(layout ? { layout } : {}) }, what);
      }
      case "microphone":
      case "camera":
      case "sensor":
        return realtimeOf(r, base, what);
      default:
        throw new InputFileError(`${what}: kind must be pulse, poisson, periodic, signal, file, microphone, camera or sensor (got ${JSON.stringify(r.kind)})`);
    }
  });
  const data = parseDataRefs(toml.data, file);
  for (const s of sources) {
    for (const name of dataNamesOf(s)) {
      if (!data.some((d) => d.name === name)) throw new InputFileError(`${file}: source '${s.name}' uses data '${name}', which isn't in a [[data]] table`);
    }
  }
  const trials = toml.trials === undefined ? undefined : parseTrials(toml.trials, sources, file);
  if (!trials) {
    const orphan = sources.find((s) => s.scope === "trial");
    if (orphan) throw new InputFileError(`${file}: source '${orphan.name}' is a trial source, but there's no [trials]`);
  }
  return {
    description: typeof toml.description === "string" ? toml.description : "",
    ...(data.length ? { data } : {}),
    sources,
    ...(trials ? { trials } : {}),
  };
}

/** `[[data]]`: unique names, and files inside the project folder (no `..`, no absolute paths). */
function parseDataRefs(raw: unknown, file: string): DataRef[] {
  if (raw === undefined) return [];
  if (!Array.isArray(raw)) throw new InputFileError(`${file}: [[data]] must be a list of tables`);
  const names = new Set<string>();
  return raw.map((d, i): DataRef => {
    const r = d as Record<string, unknown>;
    const what = `${file}: data ${i + 1}`;
    if (typeof r.name !== "string" || !r.name || /["\\]/.test(r.name)) throw new InputFileError(`${what}: name must be text without quotes, like "odour"`);
    if (typeof r.file !== "string" || !r.file) throw new InputFileError(`${what}: file must be a path in the project folder, like "odour.csv"`);
    if (r.file.includes("..") || r.file.startsWith("/") || r.file.includes("\\") || /^[A-Za-z]:/.test(r.file)) {
      throw new InputFileError(`${what}: file '${r.file}' must be inside the project folder (no .. and no absolute paths)`);
    }
    if (names.has(r.name)) throw new InputFileError(`${file}: two data files are named '${r.name}'`);
    names.add(r.name);
    return { name: r.name, file: r.file };
  });
}

/** The data names a source reads: a file source's, and the `data("name", …)` calls of a signal's formula. */
export function dataNamesOf(s: Source): string[] {
  if (s.kind === "file") return [s.data];
  if (s.kind === "signal") {
    try {
      return [...new Set(compile(s.formula).dataUses.map((u) => u.name))];
    } catch {
      return [];
    }
  }
  return [];
}

const LAYOUTS = ["order", "grid", "axis", "name"];

/** A source's position mapping (`layout`, `plane`, `axis`, `pattern`, `base`, and a signal's or file's `grid`). */
function layoutOf(r: Record<string, unknown>, kind: string, what: string): Layout | undefined {
  const name = r.layout ?? "order";
  if (typeof name !== "string" || !LAYOUTS.includes(name)) {
    throw new InputFileError(`${what}: layout must be order, grid, axis or name (got ${JSON.stringify(r.layout)})`);
  }
  const takes: Record<string, string[]> = { order: [], grid: ["plane"], axis: ["axis"], name: ["pattern", "base"] };
  const ownGrid = kind === "camera";
  if (!ownGrid) {
    takes.grid!.push("grid");
    takes.name!.push("grid");
  }
  for (const key of ["plane", "axis", "pattern", "base", ...(ownGrid ? [] : ["grid"])]) {
    if (r[key] !== undefined && !takes[name]!.includes(key)) {
      const needs = { plane: "grid", axis: "axis", pattern: "name", base: "name", grid: "grid or name" }[key];
      throw new InputFileError(`${what}: ${key} needs layout = ${needs}${name === "order" ? "" : ` (the layout is ${name})`}`);
    }
  }
  const grid = ownGrid || r.grid === undefined ? undefined : parseGrid(r.grid, `${what}: grid`);
  switch (name) {
    case "grid": {
      const plane = r.plane ?? "xy";
      if (!PLANES.includes(plane as Plane)) throw new InputFileError(`${what}: plane must be xy, xz or yz (got ${JSON.stringify(plane)})`);
      return { kind: "grid", plane: plane as Plane, ...(grid ? { grid } : {}) };
    }
    case "axis": {
      if (!AXES.includes(r.axis as Axis)) throw new InputFileError(`${what}: axis must be x, y or z (got ${JSON.stringify(r.axis)})`);
      return { kind: "axis", axis: r.axis as Axis };
    }
    case "name": {
      if (r.pattern !== undefined && typeof r.pattern !== "string") throw new InputFileError(`${what}: pattern must be text`);
      const base = r.base === undefined ? 0 : num(r.base, `${what}: base`, Number.isInteger);
      return { kind: "name", ...(r.pattern === undefined ? {} : { pattern: r.pattern as string }), base, ...(grid ? { grid } : {}) };
    }
    default:
      return undefined;
  }
}

/** The position mapping fields of a source, as TOML entries. */
function layoutToml(l: Layout | undefined, out: Record<string, unknown>) {
  if (!l) return;
  out.layout = l.kind;
  if (l.kind === "grid") {
    if (l.plane !== "xy") out.plane = l.plane;
  } else if (l.kind === "axis") out.axis = l.axis;
  else {
    if (l.pattern !== undefined) out.pattern = l.pattern;
    if (l.base) out.base = l.base;
  }
  if ("grid" in l && l.grid) out.grid = formatGrid(l.grid);
}

/** The source, if its position mapping is usable (else an InputFileError). */
function checked(s: Source, what: string): Source {
  const problem = layoutProblem(s);
  if (problem) throw new InputFileError(`${what}: ${problem}`);
  return s;
}

/** A realtime source: the settings its kind has, and `encoding`, `on_pause` and `speed` for all. */
function realtimeOf(r: Record<string, unknown>, base: Base, what: string): Source {
  const kind = r.kind as "microphone" | "camera" | "sensor";
  if (base.scope === "trial") throw new InputFileError(`${what}: a ${kind} streams for the whole run; it can't be a trial source`);
  if (r.start !== undefined || r.duration !== undefined) {
    throw new InputFileError(`${what}: a ${kind} streams while the run goes; it has no start or duration`);
  }
  const encoding = encodingOf(r.encoding, what);
  if (kind !== "sensor" && encoding.type === "spikes") throw new InputFileError(`${what}: a ${kind}'s encoding is current, rate or threshold (only a sensor can send spikes)`);
  const onPause = r.on_pause ?? "drop";
  if (onPause !== "drop" && onPause !== "buffer") throw new InputFileError(`${what}: on_pause must be "drop" or "buffer" (got ${JSON.stringify(onPause)})`);
  const speed = r.speed ?? "resample";
  if (speed !== "resample" && speed !== "refuse") throw new InputFileError(`${what}: speed must be "resample" or "refuse" (got ${JSON.stringify(speed)})`);
  const common = { ...base, start: 0, duration: null, onPause, speed } as const;
  if (kind === "sensor") return { ...common, kind, encoding };
  const sample = encoding as SampleEncoding;
  if (kind === "microphone") {
    const bands = r.bands === undefined ? undefined : num(r.bands, `${what}: bands`, (n) => Number.isInteger(n) && n >= 1);
    const layout = layoutOf(r, kind, what);
    return checked({ ...common, kind, encoding: sample, ...(bands === undefined ? {} : { bands }), ...(layout ? { layout } : {}) }, what);
  }
  const mode = r.mode ?? "luminance";
  if (mode !== "luminance" && mode !== "changes") throw new InputFileError(`${what}: mode must be "luminance" or "changes" (got ${JSON.stringify(mode)})`);
  const level = r.level === undefined ? DEFAULT_LEVEL : num(r.level, `${what}: level`, (n) => n > 0 && n <= 1);
  const layout = layoutOf(r, kind, what);
  const grid = r.grid === undefined ? { ...DEFAULT_GRID } : parseGrid(r.grid, `${what}: grid`);
  return checked({ ...common, kind, encoding: sample, mode, grid, level, ...(layout ? { layout } : {}) }, what);
}

function parseTrials(raw: unknown, sources: Source[], file: string): TrialSchedule {
  const t = (raw ?? {}) as Record<string, unknown>;
  const what = `${file}: trials`;
  const count = num(t.count, `${what}.count`, (n) => Number.isInteger(n) && n >= 1);
  const length = parseTime(t.length, `${what}.length`);
  if (!(length > 0)) throw new InputFileError(`${what}.length must be positive`);
  const gap = t.gap === undefined ? 0 : (parseRandom(t.gap, true, `${what}.gap`) ?? parseTime(t.gap, `${what}.gap`));
  const order = t.order ?? "shuffled";
  if (order !== "shuffled" && order !== "blocked" && order !== "alternating") {
    throw new InputFileError(`${what}.order must be shuffled, blocked or alternating (got ${JSON.stringify(order)})`);
  }
  const trialSources = new Set(sources.filter((s) => s.scope === "trial").map((s) => s.name));
  const list = t.condition ?? [];
  if (!Array.isArray(list)) throw new InputFileError(`${what}: [[trials.condition]] must be a list`);
  const conditions = list.map((c, i): Condition => {
    const r = c as Record<string, unknown>;
    const name = typeof r.name === "string" && r.name ? r.name : `condition ${i + 1}`;
    const names = Array.isArray(r.sources) ? r.sources : [];
    for (const n of names) {
      if (typeof n !== "string" || !trialSources.has(n)) {
        throw new InputFileError(`${what}: condition '${name}' names '${String(n)}', which isn't a trial source (scope = "trial")`);
      }
    }
    return { name, sources: names as string[] };
  });
  return {
    count,
    length,
    gap,
    start: t.start === undefined ? 0 : parseTime(t.start, `${what}.start`),
    order,
    conditions,
  };
}

/** Writes an input file. */
export function serializeInputFile(file: InputFile): string {
  const source = file.sources.map((s) => {
    const out: Record<string, unknown> = { name: s.name, kind: s.kind, neurons: { ...s.targets } };
    if (s.scope === "trial") out.scope = "trial";
    if (s.start || s.random?.start) out.start = formatTime(s.start);
    if (s.duration !== null) out.duration = formatTime(s.duration);
    if (!s.enabled) out.enabled = false;
    switch (s.kind) {
      case "pulse":
        out.at = s.at.map(formatTime);
        out.mv = s.mv;
        break;
      case "poisson":
        out.hz = s.hz;
        out.mv = s.mv;
        break;
      case "periodic":
        out.period = formatTime(s.period);
        out.mv = s.mv;
        break;
      case "signal":
        out.formula = s.formula;
        out.sample = formatTime(s.sample);
        out.encoding = encodingToml(s.encoding);
        if (s.channels !== undefined) out.channels = s.channels;
        layoutToml(s.layout, out);
        break;
      case "file":
        out.data = s.data;
        if (s.gain !== 1) out.gain = s.gain;
        if (s.sample !== 1) out.sample = formatTime(s.sample);
        out.encoding = encodingToml(s.encoding);
        if (s.channels !== undefined) out.channels = s.channels;
        layoutToml(s.layout, out);
        break;
      default: {
        // Realtime: no schedule; settings at their defaults aren't written.
        if (s.kind === "camera") {
          out.mode = s.mode;
          out.grid = formatGrid(s.grid);
          if (s.mode === "changes") out.level = s.level;
        }
        if (s.kind === "microphone" && s.bands !== undefined) out.bands = s.bands;
        out.encoding = encodingToml(s.encoding);
        if (s.kind !== "sensor") layoutToml(s.layout, out);
        if (s.onPause !== "drop") out.on_pause = s.onPause;
        if (s.speed !== "resample") out.speed = s.speed;
      }
    }
    // Random settings replace their mean.
    for (const [field, r] of Object.entries(s.random ?? {}) as Array<[RandomField, Random]>) {
      out[field] = formatRandom(r, TIME_FIELDS.includes(field));
    }
    return out;
  });
  // Written by hand rather than with the TOML library, to keep `neurons` and `encoding` inline (`neurons = { prefix =
  // "in-" }`): input files are meant to be read and edited.
  const lines: string[] = [];
  if (file.description) lines.push(`description = ${tomlValue(file.description)}`);
  for (const d of file.data ?? []) {
    if (lines.length) lines.push("");
    lines.push("[[data]]", `name = ${tomlValue(d.name)}`, `file = ${tomlValue(d.file)}`);
  }
  const t = file.trials;
  if (t) {
    if (lines.length) lines.push("");
    lines.push("[trials]");
    lines.push(`count = ${t.count}`);
    lines.push(`length = ${tomlValue(formatTime(t.length))}`);
    if (t.gap !== 0) lines.push(`gap = ${tomlValue(typeof t.gap === "number" ? formatTime(t.gap) : formatRandom(t.gap, true))}`);
    if (t.start) lines.push(`start = ${tomlValue(formatTime(t.start))}`);
    lines.push(`order = ${tomlValue(t.order)}`);
    for (const c of t.conditions) {
      lines.push("", "[[trials.condition]]", `name = ${tomlValue(c.name)}`, `sources = ${tomlValue(c.sources)}`);
    }
  }
  for (const entry of source) {
    if (lines.length) lines.push("");
    lines.push("[[source]]");
    for (const [k, v] of Object.entries(entry)) lines.push(`${k} = ${tomlValue(v)}`);
  }
  return lines.join("\n") + "\n";
}

/** A value in TOML: strings (basic strings, escaped as JSON escapes them, which TOML accepts), numbers, booleans,
 *  arrays and inline tables. */
function tomlValue(v: unknown): string {
  if (typeof v === "string") return JSON.stringify(v);
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "nan";
  if (typeof v === "boolean") return String(v);
  if (Array.isArray(v)) return `[${v.map(tomlValue).join(", ")}]`;
  if (v && typeof v === "object") {
    const items = Object.entries(v).map(([k, x]) => `${/^[A-Za-z0-9_-]+$/.test(k) ? k : JSON.stringify(k)} = ${tomlValue(x)}`);
    return `{ ${items.join(", ")} }`;
  }
  throw new Error(`can't write ${String(v)} in TOML`);
}

// ----- running -----

/** Which neurons `targets` picks in `network` (in network order). */
export function targetNeurons(targets: Targets, network: Network): number[] {
  if ("set" in targets) {
    const set = network.sets.find((s) => s.name === targets.set);
    if (!set) throw new InputFileError(`the network has no set '${targets.set}'`);
    return [...set.members].sort((a, b) => a - b);
  }
  const match = toMatch(targets);
  const compiled = compileMatch(match);
  if ("error" in compiled) throw new InputFileError(compiled.error);
  return network.neurons.filter((n) => compiled.test(n.name)).map((n) => n.index);
}

/** A prefix or regular expression target as a neuron match (a set: an empty prefix). */
export function toMatch(targets: Targets): NeuronMatch {
  return "regex" in targets
    ? { mode: "regex", pattern: targets.regex }
    : { mode: "prefix", pattern: "prefix" in targets ? targets.prefix : "" };
}

/** A neuron match as targets. */
export const fromMatch = (m: NeuronMatch): Targets => (m.mode === "regex" ? { regex: m.pattern } : { prefix: m.pattern });

/** How targets read in messages. */
export const describeTargets = (t: Targets): string => ("set" in t ? `the set '${t.set}'` : describeMatch(toMatch(t)));

/** The `data(…)` call that plays a file source: its data at the source's time, for the channel, times its gain. */
export const fileFormula = (s: { data: string; gain: number }) => `data("${s.data}", t, c)${s.gain === 1 ? "" : ` * ${s.gain}`}`;

/**
 * The engine's sources for an input file's enabled simulated sources, with targets resolved in `network` and the
 * data files they read (`data`, parsed: see `loadData`). Throws an InputFileError naming the source for one that
 * can't run (no neurons match, an unknown set, a missing data file, a layout that doesn't fit).
 */
export function engineSources(file: InputFile, network: Network, data: DataSets = new Map()): InputSource[] {
  return file.sources
    .filter((s) => s.enabled && SIMULATED.includes(s.kind))
    .map((s): InputSource => {
      const fail = (m: string) => new InputFileError(`input '${s.name}': ${m}`);
      let targets: number[];
      try {
        targets = targetNeurons(s.targets, network);
      } catch (e) {
        throw fail(e instanceof Error ? e.message : String(e));
      }
      if (!targets.length) throw fail(`no neurons have ${describeTargets(s.targets)}`);
      for (const name of dataNamesOf(s)) {
        if (!data.has(name)) throw fail(`the data file '${name}' isn't loaded`);
      }
      /** The channels of a signal or file source, by its layout. */
      const channelsOf = (c: ChannelSource, dataChannels?: number): number[][] => {
        const r = channelTargets(c, network, targets, dataChannels);
        if (!r.ok) throw fail(r.error);
        return r.channels;
      };
      const durationMs = s.duration;
      const input = ((): InputSource["input"] => {
        switch (s.kind) {
          case "pulse":
            return { type: "pulses", targets, atMs: s.at, mv: s.mv };
          case "poisson":
            return { type: "poisson", targets, rateHz: s.hz * targets.length, mv: s.mv, durationMs };
          case "periodic":
            return { type: "periodic", targets, periodMs: s.period, mv: s.mv, durationMs };
          case "signal":
            return { type: "signal", channels: channelsOf(s), formula: s.formula, sampleMs: s.sample, encoding: s.encoding, durationMs };
          case "file":
            return {
              type: "signal",
              channels: channelsOf(s, data.get(s.data)!.channels.length),
              formula: fileFormula(s),
              sampleMs: s.sample,
              encoding: s.encoding,
              durationMs,
            };
          default:
            throw new Error("not a simulated source");
        }
      })();
      return { name: s.name, startMs: s.start, input };
    });
}

// ----- the Run page's background input: a Poisson source named "background" -----

export const BACKGROUND = "background";

export type BackgroundSource = Extract<Source, { kind: "poisson" }>;

/** The file's background source, if it has one. */
export function backgroundOf(file: InputFile | null | undefined): BackgroundSource | null {
  const s = file?.sources.find((x) => x.name === BACKGROUND);
  return s?.kind === "poisson" ? s : null;
}

/** The file with its background source changed (added if missing, from `fallback`). */
export function withBackground(file: InputFile, change: Partial<BackgroundSource>, fallback: BackgroundSource): InputFile {
  const current = backgroundOf(file);
  const next: BackgroundSource = { ...(current ?? fallback), ...change, kind: "poisson", name: BACKGROUND };
  return current
    ? { ...file, sources: file.sources.map((s) => (s.name === BACKGROUND ? next : s)) }
    : { ...file, sources: [...file.sources, next] };
}

// ----- trials: expanded into sources, with the run's seed -----

/** A trial of the run (as the engine records it). */
export interface Trial {
  number: number;
  condition: string;
  startMs: number;
  endMs: number;
}

const FIELD_INDEX: Record<RandomField, number> = { start: 0, duration: 1, mv: 2, hz: 3, period: 4 };

/** A value for trial `trial` (0-based): drawn from `random` with `key`, or `value` itself. */
function drawn(value: number, random: Random | undefined, key: bigint, slot: number, trial: number): number {
  if (!random) return value;
  if ("uniform" in random) {
    const [lo, hi] = random.uniform;
    return lo + (hi - lo) * uniform(key, slot, trial, 0, 0);
  }
  const [mean, sd] = random.normal;
  return mean + sd * gauss(key, slot, trial, 0);
}

/** A source with its random settings drawn for trial `trial` (its key: the seed and its name). */
function drawSource(s: Source, seed: number, trial: number): Source {
  if (!s.random) return s;
  const key = noiseKey(seed, `trial:${s.name}`);
  const d = (field: RandomField, value: number) => drawn(value, s.random?.[field], key, FIELD_INDEX[field], trial);
  const out = { ...s, start: Math.max(0, d("start", s.start)) } as Source;
  if (s.duration !== null || s.random.duration) out.duration = Math.max(0, d("duration", s.duration ?? 0));
  if ("mv" in out) out.mv = d("mv", out.mv);
  if (out.kind === "poisson") out.hz = d("hz", out.hz);
  if (out.kind === "periodic") out.period = Math.max(0, d("period", out.period));
  delete out.random;
  return out;
}

/** The order of the trials' conditions (indices; null without conditions). */
function conditionOrder(t: TrialSchedule, seed: number): Array<number | null> {
  const n = t.conditions.length;
  if (n === 0) return Array.from({ length: t.count }, () => null);
  const blocked = t.conditions.flatMap((_, c) => Array.from({ length: t.count }, () => c));
  if (t.order === "blocked") return blocked;
  if (t.order === "alternating") return Array.from({ length: t.count * n }, (_, i) => i % n);
  // Shuffled: Fisher–Yates, from the seed.
  const key = noiseKey(seed, "trials");
  for (let i = blocked.length - 1; i > 0; i--) {
    const j = Math.floor(uniform(key, 1, i, 0, 0) * (i + 1));
    [blocked[i], blocked[j]] = [blocked[j]!, blocked[i]!];
  }
  return blocked;
}

/**
 * The file as the run gets it: its trials expanded with the run's seed into concrete sources (each trial source once
 * per trial it's on in, named "<name> #<trial>", its start and duration within the trial, its random settings
 * drawn), run sources' random settings drawn, and the list of trials. The same file and seed always give the same.
 */
export function expandTrials(file: InputFile, seed: number): { file: InputFile; trials: Trial[] } {
  const run = file.sources.filter((s) => s.scope !== "trial").map((s) => drawSource(s, seed, 0));
  const t = file.trials;
  const keep = file.data ? { data: file.data } : {};
  if (!t) return { file: { description: file.description, ...keep, sources: run }, trials: [] };
  const trialSources = file.sources.filter((s) => s.scope === "trial" && s.enabled);
  const gapKey = noiseKey(seed, "trials");
  const trials: Trial[] = [];
  const instances: Source[] = [];
  let at = t.start;
  conditionOrder(t, seed).forEach((c, k) => {
    const condition = c === null ? null : t.conditions[c]!;
    const startMs = at;
    const endMs = at + t.length;
    trials.push({ number: k + 1, condition: condition?.name ?? "", startMs, endMs });
    for (const s of trialSources) {
      if (condition && !condition.sources.includes(s.name)) continue;
      const d = drawSource(s, seed, k);
      if (d.start >= t.length) continue; // starts after the trial
      const duration = Math.min(d.duration ?? Infinity, t.length - d.start);
      if ((d.kind === "poisson" && !(d.hz > 0)) || duration <= 0) continue;
      const instance = { ...d, name: `${s.name} #${k + 1}`, start: startMs + d.start, duration } as Source;
      delete instance.scope;
      instances.push(instance);
    }
    const gap = typeof t.gap === "number" ? t.gap : Math.max(0, drawn(0, t.gap, gapKey, 0, k));
    at = endMs + gap;
  });
  return { file: { description: file.description, ...keep, sources: [...run, ...instances] }, trials };
}
