export const REALTIME: SourceKind[] = ["microphone", "camera", "sensor"];

/** A source that streams in wall-clock time while the run goes. */
export type RealtimeSource = Extract<Source, { kind: "microphone" | "camera" | "sensor" }>;
export const isRealtime = (s: Source): s is RealtimeSource => REALTIME.includes(s.kind);

export const DEFAULT_GRID: Grid = { cols: 16, rows: 16 };
export const DEFAULT_LEVEL = 0.1;
/** The largest camera grid: its channels (twice the cells for changes) must fit a batch's 16-bit channel count. */
export const MAX_GRID = 128;

/** "16x16" (columns × rows) → a grid; the multiplication sign also reads. */
export function parseGrid(text: unknown, what: string): Grid {
  const m = typeof text === "string" ? /^\s*(\d+)\s*[x×]\s*(\d+)\s*$/i.exec(text) : null;
  const [cols, rows] = m ? [Number(m[1]), Number(m[2])] : [0, 0];
  if (!m || cols < 1 || rows < 1 || cols > MAX_GRID || rows > MAX_GRID) {
    throw new InputFileError(`${what}: grid must be columns×rows like "16x16", each from 1 to ${MAX_GRID} (got ${JSON.stringify(text)})`);
  }
  return { cols, rows };
}

export const formatGrid = (g: Grid) => `${g.cols}x${g.rows}`;

