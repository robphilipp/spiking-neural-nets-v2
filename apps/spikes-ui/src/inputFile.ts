// Input files (app plan 05): a project's stimulus protocols, `*.inputs.toml` next to `project.toml`. Each holds a
// list of sources: what (the kind), where (the target neurons), how (the encoding) and when (start, duration).
//
//   description = "Gentle touch to the tail"
//
//   [[source]]
//   name = "background"
//   kind = "poisson"                 # pulse | poisson | periodic | signal; realtime: microphone | camera | sensor
//   neurons = { prefix = "in-" }     # or { regex = "^AS[HK]" }, or { set = "nociceptive" }
//   hz = 5                           # per neuron
//   mv = 12
//   start = "0 ms"                   # optional; times are "500 ms", "1 s", … or plain numbers (ms)
//   duration = "10 s"                # optional: for ever
//   enabled = true                   # optional
//
// Simulated sources (pulse, poisson, periodic, signal) are generated by the engine in simulated time: reproducible
// from the seed, at any speed. Realtime sources are kept in the file but don't run yet (plan phase I4).

import type { Encoding, InputSource, Network } from "@spikes/client";
import { parse } from "smol-toml";
import { compileMatch, describeMatch, type NeuronMatch } from "./neuronMatch";
import { compile, SignalError } from "./signal";

/** Which neurons a source drives: by name (prefix or regular expression), or a set of the network. */
export type Targets = { prefix: string } | { regex: string } | { set: string };

interface Base {
  name: string;
  targets: Targets;
  /** ms from the run's start. */
  start: number;
  /** ms; null: for ever. */
  duration: number | null;
  enabled: boolean;
}

export type SampleEncoding = Exclude<Encoding, { type: "spikes" }>;

export type Source = Base &
  (
    | { kind: "pulse"; at: number[]; mv: number }
    | { kind: "poisson"; hz: number; mv: number }
    | { kind: "periodic"; period: number; mv: number }
    | { kind: "signal"; formula: string; sample: number; encoding: SampleEncoding }
    | { kind: "microphone" | "camera" | "sensor"; encoding: Encoding }
  );

export type SourceKind = Source["kind"];

export const SIMULATED: SourceKind[] = ["pulse", "poisson", "periodic", "signal"];

export interface InputFile {
  description: string;
  sources: Source[];
}

export const emptyInputFile = (): InputFile => ({ description: "", sources: [] });

export class InputFileError extends Error {}

/** The file name for a new input file called `name`. */
export const inputFileName = (name: string) => `${name.replace(/[^\w.-]+/g, "-")}.inputs.toml`;

// ----- times -----

/** "500 ms", "1.5 s", "2 min" or a number (ms) → ms. */
export function parseTime(value: unknown, what: string): number {
  if (typeof value === "number" && Number.isFinite(value) && value >= 0) return value;
  if (typeof value === "string") {
    const m = /^\s*(\d+(?:\.\d*)?|\.\d+)\s*(ns|µs|us|ms|s|min|h)?\s*$/.exec(value);
    if (m) {
      const factor: Record<string, number> = { ns: 1e-6, "µs": 1e-3, us: 1e-3, ms: 1, s: 1e3, min: 6e4, h: 3.6e6 };
      return Number(m[1]) * factor[m[2] ?? "ms"]!;
    }
  }
  throw new InputFileError(`${what} must be a time like "500 ms" or "1 s" (got ${JSON.stringify(value)})`);
}

/** ms → "1.5 s" or "250 ms". */
export function formatTime(ms: number): string {
  return ms >= 1000 && ms % 100 === 0 ? `${ms / 1000} s` : `${ms} ms`;
}

// ----- reading and writing -----

const num = (v: unknown, what: string, ok: (n: number) => boolean = Number.isFinite): number => {
  if (typeof v !== "number" || !ok(v)) throw new InputFileError(`${what} isn't valid (${JSON.stringify(v)})`);
  return v;
};

function targetsOf(v: unknown, what: string): Targets {
  const t = (v ?? {}) as Record<string, unknown>;
  const keys = ["prefix", "regex", "set"].filter((k) => typeof t[k] === "string");
  if (keys.length !== 1) throw new InputFileError(`${what}: neurons must be { prefix = "…" }, { regex = "…" } or { set = "…" }`);
  const k = keys[0]!;
  return { [k]: t[k] as string } as Targets;
}

function encodingOf(v: unknown, what: string): Encoding {
  const e = (v ?? {}) as Record<string, unknown>;
  switch (e.kind) {
    case "current":
      return { type: "current", gainMv: num(e.gain_mv, `${what}: encoding.gain_mv`) };
    case "rate":
      return { type: "rate", maxHz: num(e.max_hz, `${what}: encoding.max_hz`, (n) => n > 0), mv: num(e.mv, `${what}: encoding.mv`) };
    case "threshold":
      return { type: "threshold", level: num(e.level, `${what}: encoding.level`, (n) => n > 0), mv: num(e.mv, `${what}: encoding.mv`) };
    case "spikes":
      return { type: "spikes", mv: num(e.mv, `${what}: encoding.mv`) };
    default:
      throw new InputFileError(`${what}: encoding.kind must be current, rate or threshold (got ${JSON.stringify(e.kind)})`);
  }
}

function encodingToml(e: Encoding): Record<string, unknown> {
  switch (e.type) {
    case "current":
      return { kind: "current", gain_mv: e.gainMv };
    case "rate":
      return { kind: "rate", max_hz: e.maxHz, mv: e.mv };
    case "threshold":
      return { kind: "threshold", level: e.level, mv: e.mv };
    case "spikes":
      return { kind: "spikes", mv: e.mv };
  }
}

/** Reads an input file (`file` names it in errors). */
export function parseInputFile(text: string, file = "the input file"): InputFile {
  let toml: Record<string, unknown>;
  try {
    toml = parse(text) as Record<string, unknown>;
  } catch (e) {
    throw new InputFileError(`${file}: ${e instanceof Error ? e.message : String(e)}`);
  }
  const list = toml.source ?? [];
  if (!Array.isArray(list)) throw new InputFileError(`${file}: [[source]] must be a list of sources`);
  const names = new Set<string>();
  const sources = list.map((raw, i): Source => {
    const r = raw as Record<string, unknown>;
    const name = typeof r.name === "string" && r.name ? r.name : `source ${i + 1}`;
    const what = `${file}: source '${name}'`;
    if (names.has(name)) throw new InputFileError(`${file}: two sources are named '${name}'`);
    names.add(name);
    const base: Base = {
      name,
      targets: targetsOf(r.neurons, what),
      start: r.start === undefined ? 0 : parseTime(r.start, `${what}: start`),
      duration: r.duration === undefined ? null : parseTime(r.duration, `${what}: duration`),
      enabled: r.enabled === undefined ? true : r.enabled === true,
    };
    switch (r.kind) {
      case "pulse": {
        const at = r.at === undefined ? [] : Array.isArray(r.at) ? r.at : [r.at];
        return { ...base, kind: "pulse", at: at.map((t) => parseTime(t, `${what}: at`)), mv: num(r.mv, `${what}: mv`) };
      }
      case "poisson":
        return { ...base, kind: "poisson", hz: num(r.hz, `${what}: hz`, (n) => n > 0), mv: num(r.mv, `${what}: mv`) };
      case "periodic":
        return { ...base, kind: "periodic", period: parseTime(r.period, `${what}: period`), mv: num(r.mv, `${what}: mv`) };
      case "signal": {
        const formula = typeof r.formula === "string" ? r.formula : "";
        try {
          compile(formula);
        } catch (e) {
          throw new InputFileError(`${what}: formula: ${e instanceof SignalError ? `${e.message} (at character ${e.position + 1})` : String(e)}`);
        }
        const encoding = encodingOf(r.encoding, what);
        if (encoding.type === "spikes") throw new InputFileError(`${what}: a signal's encoding is current, rate or threshold`);
        const sample = r.sample === undefined ? 1 : parseTime(r.sample, `${what}: sample`);
        if (!(sample > 0)) throw new InputFileError(`${what}: sample must be positive`);
        return { ...base, kind: "signal", formula, sample, encoding };
      }
      case "microphone":
      case "camera":
      case "sensor":
        return { ...base, kind: r.kind, encoding: encodingOf(r.encoding, what) };
      default:
        throw new InputFileError(`${what}: kind must be pulse, poisson, periodic, signal, microphone, camera or sensor (got ${JSON.stringify(r.kind)})`);
    }
  });
  return { description: typeof toml.description === "string" ? toml.description : "", sources };
}

/** Writes an input file. */
export function serializeInputFile(file: InputFile): string {
  const source = file.sources.map((s) => {
    const out: Record<string, unknown> = { name: s.name, kind: s.kind, neurons: { ...s.targets } };
    if (s.start) out.start = formatTime(s.start);
    if (s.duration !== null) out.duration = formatTime(s.duration);
    if (!s.enabled) out.enabled = false;
    switch (s.kind) {
      case "pulse":
        out.at = s.at.map(formatTime);
        out.mv = s.mv;
        break;
      case "poisson":
        out.hz = s.hz;
        out.mv = s.mv;
        break;
      case "periodic":
        out.period = formatTime(s.period);
        out.mv = s.mv;
        break;
      case "signal":
        out.formula = s.formula;
        out.sample = formatTime(s.sample);
        out.encoding = encodingToml(s.encoding);
        break;
      default:
        out.encoding = encodingToml(s.encoding);
    }
    return out;
  });
  // Written by hand rather than with the TOML library, to keep `neurons` and `encoding` inline (`neurons = { prefix =
  // "in-" }`): input files are meant to be read and edited.
  const lines: string[] = [];
  if (file.description) lines.push(`description = ${tomlValue(file.description)}`);
  for (const entry of source) {
    if (lines.length) lines.push("");
    lines.push("[[source]]");
    for (const [k, v] of Object.entries(entry)) lines.push(`${k} = ${tomlValue(v)}`);
  }
  return lines.join("\n") + "\n";
}

/** A value in TOML: strings (basic strings, escaped as JSON escapes them, which TOML accepts), numbers, booleans,
 *  arrays and inline tables. */
function tomlValue(v: unknown): string {
  if (typeof v === "string") return JSON.stringify(v);
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "nan";
  if (typeof v === "boolean") return String(v);
  if (Array.isArray(v)) return `[${v.map(tomlValue).join(", ")}]`;
  if (v && typeof v === "object") {
    const items = Object.entries(v).map(([k, x]) => `${/^[A-Za-z0-9_-]+$/.test(k) ? k : JSON.stringify(k)} = ${tomlValue(x)}`);
    return `{ ${items.join(", ")} }`;
  }
  throw new Error(`can't write ${String(v)} in TOML`);
}

// ----- running -----

/** Which neurons `targets` picks in `network` (in network order). */
export function targetNeurons(targets: Targets, network: Network): number[] {
  if ("set" in targets) {
    const set = network.sets.find((s) => s.name === targets.set);
    if (!set) throw new InputFileError(`the network has no set '${targets.set}'`);
    return [...set.members].sort((a, b) => a - b);
  }
  const match = toMatch(targets);
  const compiled = compileMatch(match);
  if ("error" in compiled) throw new InputFileError(compiled.error);
  return network.neurons.filter((n) => compiled.test(n.name)).map((n) => n.index);
}

/** A prefix or regular expression target as a neuron match (a set: an empty prefix). */
export function toMatch(targets: Targets): NeuronMatch {
  return "regex" in targets
    ? { mode: "regex", pattern: targets.regex }
    : { mode: "prefix", pattern: "prefix" in targets ? targets.prefix : "" };
}

/** A neuron match as targets. */
export const fromMatch = (m: NeuronMatch): Targets => (m.mode === "regex" ? { regex: m.pattern } : { prefix: m.pattern });

/** How targets read in messages. */
export const describeTargets = (t: Targets): string => ("set" in t ? `the set '${t.set}'` : describeMatch(toMatch(t)));

/**
 * The engine's sources for an input file's enabled simulated sources, with targets resolved in `network`. Throws an
 * InputFileError naming the source for one that can't run (no neurons match, an unknown set).
 */
export function engineSources(file: InputFile, network: Network): InputSource[] {
  return file.sources
    .filter((s) => s.enabled && SIMULATED.includes(s.kind))
    .map((s): InputSource => {
      let targets: number[];
      try {
        targets = targetNeurons(s.targets, network);
      } catch (e) {
        throw new InputFileError(`input '${s.name}': ${e instanceof Error ? e.message : String(e)}`);
      }
      if (!targets.length) throw new InputFileError(`input '${s.name}': no neurons have ${describeTargets(s.targets)}`);
      const durationMs = s.duration;
      const input = ((): InputSource["input"] => {
        switch (s.kind) {
          case "pulse":
            return { type: "pulses", targets, atMs: s.at, mv: s.mv };
          case "poisson":
            return { type: "poisson", targets, rateHz: s.hz * targets.length, mv: s.mv, durationMs };
          case "periodic":
            return { type: "periodic", targets, periodMs: s.period, mv: s.mv, durationMs };
          case "signal":
            return { type: "signal", channels: targets.map((i) => [i]), formula: s.formula, sampleMs: s.sample, encoding: s.encoding, durationMs };
          default:
            throw new Error("not a simulated source");
        }
      })();
      return { name: s.name, startMs: s.start, input };
    });
}

/** Sources that are in the file but don't run yet (realtime: phase I4). */
export const notRunYet = (file: InputFile): Source[] => file.sources.filter((s) => s.enabled && !SIMULATED.includes(s.kind));

// ----- the Run page's background input: a Poisson source named "background" -----

export const BACKGROUND = "background";

export type BackgroundSource = Extract<Source, { kind: "poisson" }>;

/** The file's background source, if it has one. */
export function backgroundOf(file: InputFile | null | undefined): BackgroundSource | null {
  const s = file?.sources.find((x) => x.name === BACKGROUND);
  return s?.kind === "poisson" ? s : null;
}

/** The file with its background source changed (added if missing, from `fallback`). */
export function withBackground(file: InputFile, change: Partial<BackgroundSource>, fallback: BackgroundSource): InputFile {
  const current = backgroundOf(file);
  const next: BackgroundSource = { ...(current ?? fallback), ...change, kind: "poisson", name: BACKGROUND };
  return current
    ? { ...file, sources: file.sources.map((s) => (s.name === BACKGROUND ? next : s)) }
    : { ...file, sources: [...file.sources, next] };
}
