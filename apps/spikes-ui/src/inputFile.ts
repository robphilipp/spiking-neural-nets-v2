// Input files (app plan 05): a project's stimulus protocols, `*.inputs.toml` next to `project.toml`. Each holds a
// list of sources: what (the kind), where (the target neurons), how (the encoding) and when (start, duration).
//
//   description = "Gentle touch to the tail"
//
//   [[source]]
//   name = "background"
//   kind = "poisson"                 # pulse | poisson | periodic | signal | file; realtime: microphone | camera | sensor
//   neurons = { prefix = "in-" }     # or { regex = "^AS[HK]" }, or { set = "nociceptive" }
//   hz = 5                           # per neuron
//   mv = 12
//   start = "0 ms"                   # optional; times are "500 ms", "1 s", … or plain numbers (ms)
//   duration = "10 s"                # optional: for ever
//   enabled = true                   # optional
//   scope = "trial"                  # optional: on in each trial (start, duration from the trial's start)
//
// Trials (optional) repeat the trial sources:
//
//   [trials]
//   count = 20                       # trials (per condition)
//   length = "4 s"                   # each trial
//   gap = "uniform(1 s, 2 s)"        # between trials (optional: none)
//   start = "1 s"                    # the first trial (optional: 0)
//   order = "shuffled"               # with conditions: shuffled (from the seed), blocked or alternating
//
//   [[trials.condition]]
//   name = "tail"
//   sources = ["tail touch"]         # the trial sources on in this condition (without conditions: all)
//
// A source's start, duration, mv, hz and period, and the trials' gap, can be random per trial: "uniform(a, b)" or
// "normal(mean, sd)", drawn from the run's seed (the engine's counter-based randoms: the same draws in a repeat).
//
// Data files (optional) are files of the project that formulas look up with data("name", t, c) and `file` sources play
// (CSV or WAV, see dataFile.ts; paths inside the project folder, read-only: saving doesn't rewrite them):
//
//   [[data]]
//   name = "odour"
//   file = "odour.csv"
//
//   [[source]]
//   name = "odour"
//   kind = "file"                    # plays a data file in simulated time: a signal over data("odour", t, c)
//   data = "odour"                   # a [[data]] name
//   gain = 2                         # values times this (default 1)
//   sample = "1 ms"                  # sample interval (default 1 ms; a WAV is point-sampled at it)
//   channels = 4                     # optional: at most this many channels (default: all the file's)
//   encoding = { kind = "rate", max_hz = 100, mv = 12 }
//
// A signal source can also say `channels = 4` (default: one per target neuron, or the grid's cells).
//
// Position mapping (sources with channels: microphone, camera, signal, file): which target neurons a channel drives
// (channelLayout.ts has the details). `layout = "order"` (default): channel i drives the i-th target in network order.
//
//   layout = "grid"                  # the targets' bounding box in a plane is cut into columns x rows cells; channel
//   plane = "xy"                     # (col, row), row-major, drives every target in its cell (xy | xz | yz; default xy)
//   grid = "4x4"                     # signal and file: columns x rows (default 1xN); camera: its own grid setting
//
//   layout = "axis"                  # the targets' extent along an axis is cut into N equal slabs; slab k is channel k
//   axis = "x"                       # x | y | z
//
//   layout = "name"                  # by the neurons' names: the i-th target in natural name order (input-2 before
//                                    # input-10), or with a pattern (a JavaScript regular expression):
//   pattern = "^input-(\\d)(\\d)$"     # one capture group: the channel; two: column and row of the grid (row-major)
//   base = 1                         # the names count from this (default 0)
//
// A camera's "changes" mode has on and off channels: under grid, axis and name both map onto the same cells' neurons.
// A channel may drive no neuron, and a name pattern may ignore neurons: the editor reports both.
//
// Simulated sources (pulse, poisson, periodic, signal, file) are generated by the engine in simulated time: reproducible
// from the seed, at any speed. Realtime sources (microphone, camera, sensor) stream in wall-clock time while the run
// goes (realtime.ts); they have no start or duration, and aren't trial sources. They share:
//
//   encoding = { kind = "rate", max_hz = 200, mv = 12 }   # current | rate | threshold (a sensor: also spikes)
//   on_pause = "drop"                # while the run is paused: drop what arrives (default) or buffer it
//   speed = "resample"               # the source's time follows the run's speed (default), or "refuse": it won't
//                                    # start unless the run is at speed ×1
//
//   kind = "microphone"              # one log-spaced spectrum band per target neuron (channel i drives neuron i)
//   bands = 32                       # optional: at most this many bands (the rest of the targets get nothing)
//
//   kind = "camera"                  # one channel per grid cell, in rows (cell = row × cols + column)
//   mode = "luminance"               # brightness 0–1 per cell; or "changes": 2 × cells channels, the cells' "on"
//                                    # (brightness rose) then their "off" (fell): the frame difference above `level`
//   grid = "16x16"                   # columns × rows (default 16x16)
//   level = 0.1                      # changes only: the brightness change that counts (default 0.1)
//
//   kind = "sensor"                  # a program streams into it by the source's name (docs/inputs-sensors.md):
//                                    # one channel per target neuron

