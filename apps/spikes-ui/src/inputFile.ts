/** Which neurons a source drives: by name (prefix or regular expression), or a set of the network. */
export type Targets = { prefix: string } | { regex: string } | { set: string };

/** A value drawn per trial (times in ms). */
export type Random = { uniform: [number, number] } | { normal: [number, number] };

export type RandomField = "start" | "duration" | "mv" | "hz" | "period";

/** Fields that are times (their random values' bounds are times too). */
const TIME_FIELDS: RandomField[] = ["start", "duration", "period"];

interface Base {
  name: string;
  targets: Targets;
  /** ms from the run's start (a trial source: from its trial's start). */
  start: number;
  /** ms; null: for ever (a trial source: to its trial's end). */
  duration: number | null;
  enabled: boolean;
  /** "trial": on in each trial (absent: the whole run). */
  scope?: "trial";
  /** Settings drawn per trial (their plain fields hold the mean). */
  random?: Partial<Record<RandomField, Random>>;
}

export type SampleEncoding = Exclude<Encoding, { type: "spikes" }>;

/** What a realtime source does while the run is paused: drop what arrives, or buffer it for the resume. */
export type OnPause = "drop" | "buffer";
/** How a realtime source follows the run's speed: its time scaled by it, or it won't run unless the speed is ×1. */
export type SpeedRule = "resample" | "refuse";
/** Camera: a brightness grid, or frame differences (on and off channels, like an event camera). */
export type CameraMode = "luminance" | "changes";

export interface Grid {
  cols: number;
  rows: number;
}

interface Realtime<E extends Encoding = SampleEncoding> {
  encoding: E;
  onPause: OnPause;
  speed: SpeedRule;
}

/** A data file of the project, by the name formulas and `file` sources use (`file`: its path in the project folder). */
export interface DataRef {
  name: string;
  file: string;
}

export type Source = Base &
  (
    | { kind: "pulse"; at: number[]; mv: number }
    | { kind: "poisson"; hz: number; mv: number }
    | { kind: "periodic"; period: number; mv: number }
    | { kind: "signal"; formula: string; sample: number; encoding: SampleEncoding; channels?: number; layout?: Layout }
    | { kind: "file"; data: string; gain: number; sample: number; encoding: SampleEncoding; channels?: number; layout?: Layout }
    | ({ kind: "microphone"; bands?: number; layout?: Layout } & Realtime)
    | ({ kind: "camera"; mode: CameraMode; grid: Grid; level: number; layout?: Layout } & Realtime)
    | ({ kind: "sensor" } & Realtime<Encoding>)
  );

export type SourceKind = Source["kind"];

